const pluralRules = {
  'zh-CN': new Intl.PluralRules('zh-CN'),
  'en-US': new Intl.PluralRules('en-US'),
} as const

function plural(
  locale: keyof typeof pluralRules,
  count: number,
  forms: { one: string, other: string },
): string {
  return pluralRules[locale].select(count) === 'one' ? forms.one : forms.other
}

